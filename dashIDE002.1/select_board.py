#!/usr/bin/env python3
"""Generate sketch-local IDE build settings; never edit installed libraries.

All paths are relative to this script, not the caller's current directory.
The standard-library-only selector works with Python 3 on Linux and Windows.
It does not create secrets, install dependencies, compile or upload firmware.
"""
from pathlib import Path
import argparse
import os
import tempfile

ROOT = Path(__file__).resolve().parent
# Public names and personal aliases share the exact same numeric hardware IDs.
from board_profiles import PROFILES, ALIASES, canonical_name, ide_settings



def replace_text(path, content):
    """Replace a generated file atomically; preserve no machine-specific paths."""
    handle, temporary = tempfile.mkstemp(prefix='.selection-', dir=str(path.parent))
    try:
        with os.fdopen(handle, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(content)
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def select(board, *, emit=print):
    """Persist a complete profile and advance the IDE preparation counter.

    Repeated IDE Verify/Upload actions keep that number. CLI build scripts
    continue to increment the counter independently on each compile attempt.
    """
    board = canonical_name(board)
    board_id, ide_name, fqbn = PROFILES[board]
    number = int((ROOT / 'build_nr.txt').read_text().strip()) + 1
    replace_text(ROOT / 'selected_board.h',
                 '/** Generated by select_board.py; run it again to change hardware. */\n'
                 '#pragma once\n#define DASH_SELECTED_BOARD %d\n' % board_id)
    # A changing response-file flag invalidates library/core compiler caches.
    # This is a real compiler response file, not a C header to #include.
    replace_text(ROOT / 'build_opt.h',
                 '-DDASH_IDE_PROFILE=%d\n-include ide_build.h\n' % board_id)
    replace_text(ROOT / 'board.txt', board + '\n')
    replace_text(ROOT / 'build_nr.txt', str(number) + '\n')
    replace_text(ROOT / 'build.h', '#pragma once\n#define BUILD_NR %d\n' % number)
    emit('Selected: %s (preparation #%d)' % (board, number))
    for key,value in ide_settings(board):
        emit(('Arduino IDE > Tools > Board: ' if key=='Board' else key+': ')+value)
    emit('FQBN for plain CLI validation: ' + fqbn)
    emit('Reopen dashIDE002.1.ino after switching profiles, then Verify/Upload.')
    emit('Libraries: set the IDE sketchbook to the parent directory containing libraries/.')
    return fqbn


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('board', type=canonical_name, choices=list(PROFILES),
                        help='Public hardware ID. Aliases: ' + ', '.join(ALIASES))
    args = parser.parse_args()
    select(args.board)


if __name__ == '__main__':
    main()
