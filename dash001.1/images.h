const int IMAGE_TABLE_SIZE = sizeof(IMAGE_TABLE) / sizeof(IMAGE_TABLE[0]);

int FindImageIndex(String imageName)
{
    imageName.trim();
    imageName.toLowerCase();
    for (int i = 0; i < IMAGE_TABLE_SIZE; i++)
    {
        if (imageName == IMAGE_TABLE[i].name) return i;
    }
    return -1;
}

